// Lay a string out as rows of cells: 0 off, 1 lit, 2 red. One blank column between glyphs.
export function rasterize(text) {
  const chars = [...String(text).toUpperCase()].map((c) => FONT[c] || FONT[' ']);
  const rows = Array.from({ length: 7 }, () => []);
  chars.forEach((g, i) => {
    for (let y = 0; y < 7; y++) {
      for (const ch of g[y]) rows[y].push(ch === '#' ? 1 : ch === 'r' ? 2 : 0);
      if (i < chars.length - 1) rows[y].push(0);
    }
  });
  return rows;
}
